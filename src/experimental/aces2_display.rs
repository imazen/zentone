/// How an ACES 2.0 preset encodes the rendered image for a display: the
/// encoding primaries, EOTF, and the two switches the preset files carry.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Aces2DisplayEncoding {
    /// Primaries and white the code values are expressed in
    /// (`encodingPri` in the presets). Usually equals the limiting
    /// primaries; the "D60 sim" presets limit to a D60 gamut but encode in
    /// the display's D65 one, and DCDM encodes in [`Chromaticities::XYZ_E`].
    pub encoding_primaries: Chromaticities,
    /// Inverse EOTF applied last.
    pub eotf: DisplayEotf,
    /// `scale_white`: when the limiting white differs from the encoding
    /// white, scale so the largest channel of the creative white hits `1.0`
    /// instead of clipping (the presets set this iff the whites differ).
    pub scale_white: bool,
    /// `linear_scale_factor`: multiplied into display-linear before the
    /// inverse EOTF. `1.0` for every preset except DCDM
    /// ([`DCDM_LINEAR_SCALE`]).
    pub linear_scale: f32,
}

impl Aces2DisplayEncoding {
    /// sRGB piecewise, Rec.709 primaries, D65 — the `sRGB-Piecewise` presets.
    pub const SRGB: Self = Self {
        encoding_primaries: Chromaticities::REC709,
        eotf: DisplayEotf::SrgbPiecewise,
        scale_white: false,
        linear_scale: 1.0,
    };
    /// Gamma 2.2, Rec.709 primaries, D65 — the `Gamma2pt2` presets.
    pub const REC709_GAMMA22: Self = Self {
        eotf: DisplayEotf::Gamma22,
        ..Self::SRGB
    };
    /// BT.1886, Rec.709 primaries, D65 — the `BT1886` presets.
    pub const REC709_BT1886: Self = Self {
        eotf: DisplayEotf::Bt1886,
        ..Self::SRGB
    };
    /// sRGB piecewise in P3-D65 (Display P3).
    pub const DISPLAY_P3: Self = Self {
        encoding_primaries: Chromaticities::P3_D65,
        ..Self::SRGB
    };
    /// Gamma 2.6 in P3-D65 — the P3 48-nit cinema presets.
    pub const P3_D65_GAMMA26: Self = Self {
        encoding_primaries: Chromaticities::P3_D65,
        eotf: DisplayEotf::Gamma26,
        ..Self::SRGB
    };
    /// ST 2084 (PQ) in P3-D65.
    pub const P3_D65_ST2084: Self = Self {
        encoding_primaries: Chromaticities::P3_D65,
        eotf: DisplayEotf::St2084,
        ..Self::SRGB
    };
    /// ST 2084 (PQ) in Rec.2100 — HDR10-style output.
    pub const REC2100_ST2084: Self = Self {
        encoding_primaries: Chromaticities::REC2020,
        eotf: DisplayEotf::St2084,
        ..Self::SRGB
    };
    /// HLG in Rec.2100.
    pub const REC2100_HLG: Self = Self {
        encoding_primaries: Chromaticities::REC2020,
        eotf: DisplayEotf::Hlg,
        ..Self::SRGB
    };
    /// DCDM X'Y'Z' (gamma 2.6, equal-energy white, 48 / 52.37 scale).
    pub const DCDM_GAMMA26: Self = Self {
        encoding_primaries: Chromaticities::XYZ_E,
        eotf: DisplayEotf::Gamma26,
        scale_white: false,
        linear_scale: DCDM_LINEAR_SCALE,
    };
    /// DCDM X'Y'Z' with ST 2084 (the 300-nit cinema HDR preset).
    pub const DCDM_ST2084: Self = Self {
        eotf: DisplayEotf::St2084,
        ..Self::DCDM_GAMMA26
    };

    /// This encoding with `scale_white` set — what the "D60 sim" presets
    /// (a D60 limiting gamut encoded in a D65 display) use.
    #[must_use]
    pub const fn with_white_scaling(self) -> Self {
        Self {
            scale_white: true,
            ..self
        }
    }
}

impl Default for Aces2DisplayEncoding {
    /// [`Self::SRGB`].
    fn default() -> Self {
        Self::SRGB
    }
}

/// An ACES 2.0 output preset: the rendering ([`Aces2OutputTransform`]) plus
/// the display encoding, ACES2065-1 in and display code values out — the
/// whole of an `Output.Academy.*` CTL file.
///
/// Implements [`ToneMap`] with `map_rgb` = [`forward`](Self::forward), so
/// the output is *encoded* (non-linear) code values, unlike every other
/// zentone tonemapper. Use [`Aces2OutputTransform`] directly for
/// display-linear output.
#[derive(Debug, Clone)]
pub struct Aces2DisplayTransform {
    ot: Aces2OutputTransform,
    config: Aces2Config,
    encoding: Aces2DisplayEncoding,
    limit_to_display: Mat3,
    display_to_limit: Mat3,
    /// `1 / largest channel of the limiting white in the encoding primaries`
    /// when `scale_white`, else `1`.
    white_scale: f32,
    clamp_max: f32,
}

impl Aces2DisplayTransform {
    /// Build the rendering for `config` and wrap it in `encoding`.
    ///
    /// # Errors
    ///
    /// Everything [`Aces2OutputTransform::new`] rejects, plus
    /// `Error::InvalidConfig` for degenerate encoding primaries or a
    /// non-positive / non-finite `linear_scale`.
    pub fn new(config: Aces2Config, encoding: Aces2DisplayEncoding) -> Result<Self> {
        Self::from_output_transform(Aces2OutputTransform::new(config)?, config, encoding)
    }

    /// Wrap an already-built rendering. `config` must be the one `ot` was
    /// built from (it is not re-derived; it feeds the transform ID and the
    /// peak clamp).
    ///
    /// # Errors
    ///
    /// `Error::InvalidConfig` if `config.peak_luminance` disagrees with
    /// `ot`, the encoding primaries are degenerate, or `linear_scale` is
    /// not a positive finite number.
    pub fn from_output_transform(
        ot: Aces2OutputTransform,
        config: Aces2Config,
        encoding: Aces2DisplayEncoding,
    ) -> Result<Self> {
        if ot.peak_luminance() != config.peak_luminance {
            return Err(Error::InvalidConfig(
                "ACES 2.0 display: config.peak_luminance does not match the output transform",
            ));
        }
        if !(encoding.linear_scale.is_finite() && encoding.linear_scale > 0.0) {
            return Err(Error::InvalidConfig(
                "ACES 2.0 display: linear_scale must be finite and > 0",
            ));
        }
        let bad = || Error::InvalidConfig("ACES 2.0 display: encoding primaries are degenerate");
        let limit_to_display = mul_mm(
            &rgb_to_xyz_matrix(&config.limiting_primaries, 1.0),
            &xyz_to_rgb_matrix(&encoding.encoding_primaries, 1.0).ok_or_else(bad)?,
        );
        let display_to_limit = invert(&limit_to_display).ok_or_else(bad)?;
        let white_scale = if encoding.scale_white {
            let w = mul_vm([1.0; 3], &limit_to_display);
            let largest = w[0].max(w[1]).max(w[2]);
            if !(largest.is_finite() && largest > 0.0) {
                return Err(bad());
            }
            1.0 / largest
        } else {
            1.0
        };
        Ok(Self {
            ot,
            config,
            encoding,
            limit_to_display,
            display_to_limit,
            white_scale,
            clamp_max: config.peak_luminance / REF_LUMINANCE,
        })
    }

    /// The wrapped rendering.
    #[must_use]
    pub fn output_transform(&self) -> &Aces2OutputTransform {
        &self.ot
    }

    /// The rendering configuration.
    #[must_use]
    pub fn config(&self) -> &Aces2Config {
        &self.config
    }

    /// The display encoding.
    #[must_use]
    pub fn encoding(&self) -> &Aces2DisplayEncoding {
        &self.encoding
    }

    /// Full preset: ACES2065-1 → display code values.
    #[must_use]
    pub fn forward(&self, aces: [f32; 3]) -> [f32; 3] {
        self.encode_display(self.ot.forward(aces))
    }

    /// Full inverse preset: display code values → ACES2065-1.
    #[must_use]
    pub fn inverse(&self, code_values: [f32; 3]) -> [f32; 3] {
        self.ot.inverse(self.decode_display(code_values))
    }

    /// The encoding half alone: display-linear RGB in the limiting
    /// primaries (what [`Aces2OutputTransform::forward`] returns) → code
    /// values. Peak clamp, white scaling, primaries matrix, linear scale,
    /// inverse EOTF.
    #[must_use]
    pub fn encode_display(&self, rgb_limit: [f32; 3]) -> [f32; 3] {
        let mut rgb = [
            clamp_nan_to_zero(rgb_limit[0], self.clamp_max),
            clamp_nan_to_zero(rgb_limit[1], self.clamp_max),
            clamp_nan_to_zero(rgb_limit[2], self.clamp_max),
        ];
        if self.encoding.scale_white {
            for c in &mut rgb {
                *c *= self.white_scale;
            }
        }
        let display = mul_vm(rgb, &self.limit_to_display);
        let s = self.encoding.linear_scale;
        let scaled = [
            (display[0] * s).max(0.0),
            (display[1] * s).max(0.0),
            (display[2] * s).max(0.0),
        ];
        match self.encoding.eotf {
            // HLG's inverse OOTF is a per-pixel (luminance) operation.
            DisplayEotf::Hlg => st2084_to_hlg_1000nits_rgb([
                y_to_st2084(scaled[0] * REF_LUMINANCE),
                y_to_st2084(scaled[1] * REF_LUMINANCE),
                y_to_st2084(scaled[2] * REF_LUMINANCE),
            ]),
            eotf => eotf.encode_rgb(scaled),
        }
    }

    /// The decoding half alone: code values → display-linear RGB in the
    /// limiting primaries, clamped to `[0, peak_luminance / 100]` (what
    /// [`Aces2OutputTransform::inverse`] expects).
    #[must_use]
    pub fn decode_display(&self, code_values: [f32; 3]) -> [f32; 3] {
        let display = match self.encoding.eotf {
            DisplayEotf::Hlg => {
                let pq = hlg_to_st2084_1000nits_rgb(code_values);
                [
                    st2084_to_y(pq[0]) / REF_LUMINANCE,
                    st2084_to_y(pq[1]) / REF_LUMINANCE,
                    st2084_to_y(pq[2]) / REF_LUMINANCE,
                ]
            }
            eotf => eotf.decode_rgb(code_values),
        };
        let inv_s = 1.0 / self.encoding.linear_scale;
        let mut rgb = mul_vm(
            [display[0] * inv_s, display[1] * inv_s, display[2] * inv_s],
            &self.display_to_limit,
        );
        if self.encoding.scale_white {
            let inv = 1.0 / self.white_scale;
            for c in &mut rgb {
                *c *= inv;
            }
        }
        [
            clamp_nan_to_zero(rgb[0], self.clamp_max),
            clamp_nan_to_zero(rgb[1], self.clamp_max),
            clamp_nan_to_zero(rgb[2], self.clamp_max),
        ]
    }

    /// The `ACEStransformID` of the matching `Output.Academy.*` preset in
    /// <https://github.com/aces-aswf/aces-output>, e.g.
    /// `urn:ampas:aces:transformId:v2.0:Output.Academy.Rec709-D65_100nit_in_Rec709-D65_sRGB-Piecewise.a2.v1`,
    /// or `None` when this configuration is not one of the 54 shipped
    /// presets (unknown primaries, an unlisted peak, `Linear`, or
    /// `scale_white` / `linear_scale` set differently from the preset).
    #[must_use]
    pub fn transform_id(&self) -> Option<&'static str> {
        let name = self.preset_name()?;
        ACES_OUTPUT_TRANSFORM_IDS.iter().copied().find(|id| {
            id.strip_prefix(TRANSFORM_ID_PREFIX)
                .and_then(|s| s.strip_suffix(".a2.v1"))
                == Some(name.as_str())
        })
    }

    /// `<Limit>_<nit>nit_in_<Encoding>_<EOTF>` for the preset naming scheme.
    fn preset_name(&self) -> Option<String> {
        let c = self.config;
        let e = self.encoding;
        let limit = if c.limiting_primaries == Chromaticities::REC709 {
            "Rec709-D65"
        } else if c.limiting_primaries == Chromaticities::REC709_D60 {
            "Rec709-D60"
        } else if c.limiting_primaries == Chromaticities::P3_D65 {
            "P3-D65"
        } else if c.limiting_primaries == Chromaticities::P3_D60 {
            "P3-D60"
        } else if c.limiting_primaries == Chromaticities::REC2020 {
            "Rec2100-D65"
        } else if c.limiting_primaries == Chromaticities::REC2020_D60 {
            "Rec2100-D60"
        } else {
            return None;
        };
        let (encoding, dcdm) = if e.encoding_primaries == Chromaticities::REC709 {
            ("Rec709-D65", false)
        } else if e.encoding_primaries == Chromaticities::P3_D65 {
            ("P3-D65", false)
        } else if e.encoding_primaries == Chromaticities::REC2020 {
            ("Rec2100-D65", false)
        } else if e.encoding_primaries == Chromaticities::XYZ_E {
            ("XYZ-E", true)
        } else {
            return None;
        };
        let whites_differ = c.limiting_primaries.white != e.encoding_primaries.white;
        if e.scale_white != (whites_differ && !dcdm) {
            return None;
        }
        let expected_scale = if dcdm { DCDM_LINEAR_SCALE } else { 1.0 };
        if (e.linear_scale - expected_scale).abs() > 1e-6 {
            return None;
        }
        // DCDM presets are named by the projector peak (48 / 300 cd/m²) while
        // the tonescale targets that × 100/48.
        let nits = if dcdm {
            c.peak_luminance * 0.48
        } else {
            c.peak_luminance
        };
        if !(nits.is_finite() && nits >= 1.0 && (nits - libm::roundf(nits)).abs() < 1e-3) {
            return None;
        }
        let eotf = e.eotf.transform_id_token()?;
        Some(format!(
            "Output.Academy.{limit}_{}nit_in_{encoding}_{eotf}",
            libm::roundf(nits) as u32
        ))
    }
}

impl ToneMap for Aces2DisplayTransform {
    /// [`forward`](Self::forward): ACES2065-1 in, display **code values**
    /// (encoded, not linear) out.
    #[inline]
    fn map_rgb(&self, rgb: [f32; 3]) -> [f32; 3] {
        self.forward(rgb)
    }
}

/// `clamp_f3(rgb, 0, max)` with NaN landing on `0`.
#[inline]
fn clamp_nan_to_zero(v: f32, max: f32) -> f32 {
    v.max(0.0).min(max)
}

