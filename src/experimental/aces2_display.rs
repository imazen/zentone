//! ACES 2.0 display encoding — the wrapper the ACES output presets put
//! around the rendering ([`Aces2OutputTransform`]).
//!
//! A port of `Lib.Academy.DisplayEncoding.ctl` plus the `main()` of the
//! preset files in <https://github.com/aces-aswf/aces-output> (`main` as of
//! 2025-10). For a forward preset the CTL does:
//!
//! ```text
//! ACES2065-1 ─ outputTransform_fwd (Aces2OutputTransform::forward)
//!   → clamp to [0, peak_luminance / 100]
//!   → white scaling (only when the limiting white ≠ the encoding white)
//!   → limiting primaries → encoding primaries (plain matrix, no adaptation)
//!   → × linear_scale (48 / 52.37 for DCDM, else 1)
//!   → inverse EOTF (sRGB, gamma 2.2 / 2.6, BT.1886, ST 2084, HLG, or none)
//! ```
//!
//! and the inverse preset runs the same steps backwards. The inverse
//! white-scale step in the CTL clamps to `[0, 1]`; this port clamps to
//! `[0, peak_luminance / 100]` (identical for SDR presets, and what the
//! next step clamps to anyway) so HDR "D60 sim" presets invert above 100
//! cd/m² — the behaviour OpenColorIO's builtins have.
//!
//! **Parity.** Held to OpenColorIO 2.5's `ACES-OUTPUT - … _2.0` builtins
//! composed with its `DISPLAY - CIE-XYZ-D65_to_…` builtins on
//! `reference-checks/golden/aces2_ocio_display_encoding{,_inv}.csv`
//! (generated by `reference-checks/aces_ocio_encodings_reference.py`).

use alloc::format;
use alloc::string::String;

use super::aces2::{
    Aces2Config, Aces2OutputTransform, Chromaticities, Mat3, invert, mul_mm, mul_vm,
    rgb_to_xyz_matrix, xyz_to_rgb_matrix,
};
use crate::{Error, Result, ToneMap};
use libm::{expf, logf, powf, sqrtf};

/// `ref_luminance` in the CTL: display-linear `1.0` is 100 cd/m².
const REF_LUMINANCE: f32 = 100.0;

// SMPTE ST 2084 constants.
const PQ_M1: f32 = 0.1593017578125;
const PQ_M2: f32 = 78.84375;
const PQ_C1: f32 = 0.8359375;
const PQ_C2: f32 = 18.8515625;
const PQ_C3: f32 = 18.6875;
const PQ_C: f32 = 10000.0;

// ITU-R BT.2100 HLG constants.
const HLG_A: f32 = 0.17883277;
const HLG_B: f32 = 0.28466892;
const HLG_C: f32 = 0.55991073;

/// `linear_scale_factor` of the DCDM (X'Y'Z') presets: 48 cd/m² peak
/// expressed against the 52.37 cd/m² the 2.6-gamma encoding reaches.
pub const DCDM_LINEAR_SCALE: f32 = 48.0 / 52.37;

/// Display EOTF an ACES 2.0 preset encodes for (`eotf_enum` in the CTL).
///
/// [`encode`](Self::encode) is the *inverse* EOTF (display-linear → code
/// value); [`decode`](Self::decode) is the EOTF. Display-linear `1.0` is
/// 100 cd/m² for the absolute encodings (ST 2084, HLG) and the display peak
/// for the relative ones.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum DisplayEotf {
    /// No encoding: code value = display-linear.
    Linear,
    /// SMPTE ST 2084 (PQ), absolute: `1.0` display-linear = 100 cd/m².
    St2084,
    /// ITU-R BT.2100 HLG, via the BT.2390 §7 PQ→HLG conversion at 1000
    /// cd/m² nominal peak (as the CTL does it).
    Hlg,
    /// Pure power 2.6 (DCDM / cinema).
    Gamma26,
    /// ITU-R BT.1886 with γ = 2.4, `Lw = 1`, `Lb = 0` (a pure power 2.4).
    Bt1886,
    /// Pure power 2.2.
    Gamma22,
    /// IEC 61966-2-1:1999 sRGB piecewise curve.
    SrgbPiecewise,
}

impl DisplayEotf {
    /// Inverse EOTF: display-linear → code value (`eotf_inv` in the CTL).
    /// Negative input clamps to `0` first, as the CTL does.
    #[must_use]
    pub fn encode(self, linear: f32) -> f32 {
        let v = linear.max(0.0);
        match self {
            Self::Linear => v,
            Self::St2084 => y_to_st2084(v * REF_LUMINANCE),
            Self::Hlg => st2084_to_hlg_1000nits(y_to_st2084(v * REF_LUMINANCE)),
            Self::Gamma26 => powf(v, 1.0 / 2.6),
            Self::Bt1886 => bt1886_inv(v, 2.4),
            Self::Gamma22 => powf(v, 1.0 / 2.2),
            Self::SrgbPiecewise => moncurve_inv(v, 2.4, 0.055),
        }
    }

    /// EOTF: code value → display-linear (`eotf` in the CTL).
    #[must_use]
    pub fn decode(self, code_value: f32) -> f32 {
        match self {
            Self::Linear => code_value,
            Self::St2084 => st2084_to_y(code_value) / REF_LUMINANCE,
            Self::Hlg => st2084_to_y(hlg_to_st2084_1000nits(code_value)) / REF_LUMINANCE,
            Self::Gamma26 => powf(code_value, 2.6),
            Self::Bt1886 => bt1886_fwd(code_value, 2.4),
            Self::Gamma22 => powf(code_value, 2.2),
            Self::SrgbPiecewise => moncurve_fwd(code_value, 2.4, 0.055),
        }
    }

    /// Encode all three channels.
    #[must_use]
    pub fn encode_rgb(self, rgb: [f32; 3]) -> [f32; 3] {
        [
            self.encode(rgb[0]),
            self.encode(rgb[1]),
            self.encode(rgb[2]),
        ]
    }

    /// Decode all three channels.
    #[must_use]
    pub fn decode_rgb(self, cv: [f32; 3]) -> [f32; 3] {
        [self.decode(cv[0]), self.decode(cv[1]), self.decode(cv[2])]
    }

    /// The EOTF's token in an ACES transform ID (`None` for `Linear`,
    /// which no shipped preset uses).
    fn transform_id_token(self) -> Option<&'static str> {
        Some(match self {
            Self::Linear => return None,
            Self::St2084 => "ST2084",
            Self::Hlg => "HLG",
            Self::Gamma26 => "Gamma2pt6",
            Self::Bt1886 => "BT1886",
            Self::Gamma22 => "Gamma2pt2",
            Self::SrgbPiecewise => "sRGB-Piecewise",
        })
    }
}

// -- transfer functions (Lib.Academy.DisplayEncoding.ctl) -------------------

/// `moncurve_fwd`: code value → linear, γ = 2.4 / offset 0.055 is sRGB.
fn moncurve_fwd(x: f32, gamma: f32, offs: f32) -> f32 {
    let fs = ((gamma - 1.0) / offs) * powf(offs * gamma / ((gamma - 1.0) * (1.0 + offs)), gamma);
    let xb = offs / (gamma - 1.0);
    if x >= xb {
        powf((x + offs) / (1.0 + offs), gamma)
    } else {
        x * fs
    }
}

/// `moncurve_inv`: linear → code value.
fn moncurve_inv(y: f32, gamma: f32, offs: f32) -> f32 {
    let yb = powf(offs * gamma / ((gamma - 1.0) * (1.0 + offs)), gamma);
    let rs = powf((gamma - 1.0) / offs, gamma - 1.0) * powf((1.0 + offs) / gamma, gamma);
    if y >= yb {
        (1.0 + offs) * powf(y, 1.0 / gamma) - offs
    } else {
        y * rs
    }
}

/// `bt1886_fwd` with `Lw = 1`, `Lb = 0`: `L = max(V, 0)^γ`.
fn bt1886_fwd(v: f32, gamma: f32) -> f32 {
    powf(v.max(0.0), gamma)
}

/// `bt1886_inv` with `Lw = 1`, `Lb = 0`: `V = max(L, 0)^(1/γ)`.
fn bt1886_inv(l: f32, gamma: f32) -> f32 {
    powf(l.max(0.0), 1.0 / gamma)
}

/// `ST2084_to_Y`: PQ code value (full range) → cd/m².
fn st2084_to_y(n: f32) -> f32 {
    let np = powf(n, 1.0 / PQ_M2);
    let l = (np - PQ_C1).max(0.0) / (PQ_C2 - PQ_C3 * np);
    powf(l, 1.0 / PQ_M1) * PQ_C
}

/// `Y_to_ST2084`: cd/m² → PQ code value (full range).
fn y_to_st2084(c: f32) -> f32 {
    let lm = powf(c / PQ_C, PQ_M1);
    powf((PQ_C1 + PQ_C2 * lm) / (1.0 + PQ_C3 * lm), PQ_M2)
}

/// `ST2084_to_HLG_1000nits`, per channel. The CTL computes the inverse OOTF
/// from the pixel's BT.2020 luminance, so this takes the whole triple.
fn st2084_to_hlg_1000nits_rgb(pq: [f32; 3]) -> [f32; 3] {
    let display = [st2084_to_y(pq[0]), st2084_to_y(pq[1]), st2084_to_y(pq[2])];
    let y_d = 0.2627 * display[0] + 0.6780 * display[1] + 0.0593 * display[2];
    const L_W: f32 = 1000.0;
    const GAMMA: f32 = 1.2;
    let mut scene = [0.0f32; 3];
    if y_d != 0.0 {
        let k = powf(y_d / L_W, (1.0 - GAMMA) / GAMMA);
        for c in 0..3 {
            scene[c] = k * (display[c] / L_W);
        }
    }
    [hlg_oetf(scene[0]), hlg_oetf(scene[1]), hlg_oetf(scene[2])]
}

/// Scalar convenience used by [`DisplayEotf::encode`]: for a single channel
/// the inverse OOTF's luminance is the channel itself scaled by its BT.2020
/// weight — which is *not* what the CTL does per pixel. Per-pixel encoding
/// goes through [`st2084_to_hlg_1000nits_rgb`]; this scalar form is only
/// exact for neutral pixels and exists so the enum has a per-channel API.
fn st2084_to_hlg_1000nits(pq: f32) -> f32 {
    st2084_to_hlg_1000nits_rgb([pq; 3])[0]
}

/// `HLG_to_ST2084_1000nits`, whole triple (OOTF needs the luminance).
fn hlg_to_st2084_1000nits_rgb(hlg: [f32; 3]) -> [f32; 3] {
    let scene = [hlg_eotf(hlg[0]), hlg_eotf(hlg[1]), hlg_eotf(hlg[2])];
    let y_s = 0.2627 * scene[0] + 0.6780 * scene[1] + 0.0593 * scene[2];
    const L_W: f32 = 1000.0;
    const GAMMA: f32 = 1.2;
    let k = L_W * powf(y_s, GAMMA - 1.0);
    [
        y_to_st2084(k * scene[0]),
        y_to_st2084(k * scene[1]),
        y_to_st2084(k * scene[2]),
    ]
}

fn hlg_to_st2084_1000nits(hlg: f32) -> f32 {
    hlg_to_st2084_1000nits_rgb([hlg; 3])[0]
}

/// HLG OETF: scene-linear (`1/12` = nominal peak) → signal.
fn hlg_oetf(x: f32) -> f32 {
    if x <= 1.0 / 12.0 {
        sqrtf(3.0 * x)
    } else {
        HLG_A * logf(12.0 * x - HLG_B) + HLG_C
    }
}

/// HLG inverse OETF: signal → scene-linear.
fn hlg_eotf(v: f32) -> f32 {
    if (0.0..=0.5).contains(&v) {
        v * v / 3.0
    } else {
        (expf((v - HLG_C) / HLG_A) + HLG_B) / 12.0
    }
}

