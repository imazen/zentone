    fn rows(csv: &str) -> Vec<Vec<&str>> {
        csv.lines()
            .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
            .map(|l| l.split(',').collect())
            .collect()
    }

    fn f(s: &str) -> f32 {
        s.trim()
            .parse()
            .unwrap_or_else(|_| panic!("bad float {s:?}"))
    }

    /// The golden presets, as (config, encoding) pairs.
    fn preset(name: &str) -> (Aces2Config, Aces2DisplayEncoding) {
        let cfg = |peak, prims| Aces2Config {
            peak_luminance: peak,
            limiting_primaries: prims,
        };
        match name {
            "rec709_100_srgb" => (
                cfg(100.0, Chromaticities::REC709),
                Aces2DisplayEncoding::SRGB,
            ),
            "rec709_100_bt1886" => (
                cfg(100.0, Chromaticities::REC709),
                Aces2DisplayEncoding::REC709_BT1886,
            ),
            "rec709_100_g22" => (
                cfg(100.0, Chromaticities::REC709),
                Aces2DisplayEncoding::REC709_GAMMA22,
            ),
            "p3d65_100_g26" => (
                cfg(100.0, Chromaticities::P3_D65),
                Aces2DisplayEncoding::P3_D65_GAMMA26,
            ),
            "p3d65_1000_pq" => (
                cfg(1000.0, Chromaticities::P3_D65),
                Aces2DisplayEncoding::P3_D65_ST2084,
            ),
            "rec2020_1000_pq" => (
                cfg(1000.0, Chromaticities::REC2020),
                Aces2DisplayEncoding::REC2100_ST2084,
            ),
            "p3d65_1000_hlg_rec2100" => (
                cfg(1000.0, Chromaticities::P3_D65),
                Aces2DisplayEncoding::REC2100_HLG,
            ),
            "rec709d60_100_srgb" => (
                cfg(100.0, Chromaticities::REC709_D60),
                Aces2DisplayEncoding::SRGB.with_white_scaling(),
            ),
            "p3d60_1000_pq_rec2100" => (
                cfg(1000.0, Chromaticities::P3_D60),
                Aces2DisplayEncoding::REC2100_ST2084.with_white_scaling(),
            ),
            other => panic!("unknown preset {other}"),
        }
    }

    fn transforms(csv: &str) -> Vec<(&str, Aces2DisplayTransform)> {
        let mut out: Vec<(&str, Aces2DisplayTransform)> = Vec::new();
        for r in rows(csv) {
            if out.iter().all(|(n, _)| *n != r[0]) {
                let (cfg, enc) = preset(r[0]);
                out.push((r[0], Aces2DisplayTransform::new(cfg, enc).unwrap()));
            }
        }
        out
    }

    #[test]
    fn display_encoding_matches_ocio() {
        let ts = transforms(DISPLAY_CSV);
        let mut checked = 0;
        for r in rows(DISPLAY_CSV) {
            let t = &ts.iter().find(|(n, _)| *n == r[0]).unwrap().1;
            let aces = [f(r[1]), f(r[2]), f(r[3])];
            let want = [f(r[4]), f(r[5]), f(r[6])];
            let got = t.forward(aces);
            for c in 0..3 {
                // Code values are in [0, 1]; the rendering agrees with OCIO
                // to ~1e-3 display-linear, which the inverse EOTFs stretch
                // near black (sRGB's linear toe ×12.9, PQ's steep foot).
                assert!(
                    (got[c] - want[c]).abs() <= 3e-3,
                    "{} {aces:?}: {got:?} vs {want:?}",
                    r[0]
                );
            }
            checked += 1;
        }
        assert!(checked >= 200, "only {checked} rows compared");
    }

    #[test]
    fn display_decoding_matches_ocio() {
        let ts = transforms(DISPLAY_INV_CSV);
        let mut checked = 0;
        let mut skipped = 0;
        for r in rows(DISPLAY_INV_CSV) {
            let t = &ts.iter().find(|(n, _)| *n == r[0]).unwrap().1;
            let cv = [f(r[1]), f(r[2]), f(r[3])];
            let want = [f(r[4]), f(r[5]), f(r[6])];
            // OpenColorIO's HLG display is a LUT around its own HLG curve
            // (input scaled so the OETF is `sqrt(x)`), which decodes
            // near-black code values differently from the CTL formula:
            // measured 30% relative disagreement at cv ≈ 0.002 (display
            // linear ~1e-6, i.e. 1e-4 cd/m²) with identical display-linear
            // input fed to both. Those rows are skipped, and counted.
            if t.encoding().eotf == DisplayEotf::Hlg && cv.iter().all(|&c| c < 0.005) {
                skipped += 1;
                continue;
            }
            let got = t.inverse(cv);
            // Same conditioning story as the rendering's inverse test:
            // relative to the pixel magnitude, loose where the forward
            // saturated (peak white, channels pinned at zero).
            let scale = want.iter().fold(1e-3f32, |m, v| m.max(v.abs()));
            for c in 0..3 {
                assert!(
                    (got[c] - want[c]).abs() <= 2e-2 * scale,
                    "{} cv {cv:?}: inverse {got:?} vs {want:?}",
                    r[0]
                );
            }
            checked += 1;
        }
        assert!(checked >= 200, "only {checked} rows compared");
        assert!(skipped <= 3, "{skipped} near-black HLG rows skipped");
    }

    #[test]
    fn eotf_pairs_round_trip() {
        let all = [
            DisplayEotf::Linear,
            DisplayEotf::St2084,
            DisplayEotf::Hlg,
            DisplayEotf::Gamma26,
            DisplayEotf::Bt1886,
            DisplayEotf::Gamma22,
            DisplayEotf::SrgbPiecewise,
        ];
        for eotf in all {
            for i in 0..=200 {
                let lin = i as f32 / 200.0
                    * if eotf == DisplayEotf::St2084 {
                        100.0
                    } else {
                        1.0
                    };
                let cv = eotf.encode(lin);
                assert!((0.0..=1.0001).contains(&cv), "{eotf:?}({lin}) = {cv}");
                let back = eotf.decode(cv);
                assert!(
                    (back - lin).abs() <= 1e-4 + lin * 2e-4,
                    "{eotf:?}: {lin} -> {cv} -> {back}"
                );
            }
            // Negative display-linear clamps to 0 first (PQ's code value for
            // 0 cd/m² is c1^m2 ≈ 7e-7, not 0).
            assert_eq!(eotf.encode(-0.5), eotf.encode(0.0), "{eotf:?}");
        }
        // Anchors: sRGB 0.5 code value ≈ 0.2140 linear; PQ 100 nits = 0.508.
        assert!((DisplayEotf::SrgbPiecewise.decode(0.5) - 0.214_041).abs() < 1e-5);
        assert!((DisplayEotf::St2084.encode(1.0) - 0.508_078).abs() < 1e-5);
    }

    #[test]
    fn white_scaling_fits_d60_white_into_d65_display() {
        // Rec709-D60 limiting, encoded in Rec709-D65 with scaling: the
        // creative white (1,1,1) must land with its largest channel at
        // exactly 1.0 and no channel above it.
        let t = Aces2DisplayTransform::new(
            Aces2Config {
                peak_luminance: 100.0,
                limiting_primaries: Chromaticities::REC709_D60,
            },
            Aces2DisplayEncoding::SRGB.with_white_scaling(),
        )
        .unwrap();
        let cv = t.encode_display([1.0; 3]);
        let max = cv[0].max(cv[1]).max(cv[2]);
        assert!((max - 1.0).abs() < 1e-5, "{cv:?}");
        assert!(cv.iter().all(|&c| c <= 1.0 + 1e-6), "{cv:?}");
        // D60 white is warmer than D65: red above blue.
        assert!(cv[0] > cv[2], "{cv:?}");
        // Without scaling the red channel would clip above 1.0 in the
        // encoding — the difference the switch exists for.
        let unscaled = Aces2DisplayTransform::new(*t.config(), Aces2DisplayEncoding::SRGB).unwrap();
        let raw = unscaled.encode_display([1.0; 3]);
        assert!(raw[0] > 1.0 - 1e-6 && raw[2] < 1.0, "{raw:?}");
        // Decoding undoes the scaling.
        let back = t.decode_display(cv);
        assert!(back.iter().all(|&c| (c - 1.0).abs() < 1e-4), "{back:?}");
    }

