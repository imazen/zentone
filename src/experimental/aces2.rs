/// ACES 2.0 Output Transform: ACES2065-1 (AP0) linear in, display-linear RGB
/// in the limiting primaries out (`1.0` = 100 cd/m²).
///
/// Construct once per output configuration with [`Aces2OutputTransform::new`]
/// — building the gamut tables costs on the order of 10⁵ CAM evaluations —
/// then apply per pixel via [`forward`](Self::forward) /
/// [`inverse`](Self::inverse), or through the [`ToneMap`] trait (whose
/// `map_rgb` is `forward`).
///
/// Input is ACES2065-1: convert from other scene-linear encodings with a
/// primaries matrix first (e.g. via `zenpixels-convert` or
/// [`crate::gamut::apply_matrix`]). Output is display-linear; apply the
/// display's OETF afterwards. For SDR 100-nit targets that means `1.0` is
/// diffuse white; for a 1000-nit PQ target the output reaches `10.0`.
#[derive(Debug, Clone)]
pub struct Aces2OutputTransform {
    peak_luminance: f32,
    input_params: JmhParams,
    limit_params: JmhParams,
    ts: TsParams,
    ap0_to_ap1: Mat3,
    ap1_to_ap0: Mat3,
    limit_j_max: f32,
    model_gamma_inv: f32,
    // Chroma compression.
    sat: f32,
    sat_thr: f32,
    compr: f32,
    chroma_compress_scale: f32,
    // Gamut compression.
    mid_j: f32,
    focus_dist: f32,
    lower_hull_gamma_inv: f32,
    hue_linearity_search_range: [i32; 2],
    tables: Box<Tables>,
}

impl Aces2OutputTransform {
    /// Build the transform for `config` (`init_ODTParams` in the CTL).
    ///
    /// # Errors
    ///
    /// `Error::InvalidConfig` if `peak_luminance` is not finite or below 1,
    /// or if the limiting primaries are degenerate (non-invertible).
    pub fn new(config: Aces2Config) -> Result<Self> {
        let peak = config.peak_luminance;
        if !peak.is_finite() || peak < 1.0 {
            return Err(Error::InvalidConfig(
                "ACES 2.0: peak_luminance must be finite and >= 1 cd/m^2",
            ));
        }
        let bad_prims = || Error::InvalidConfig("ACES 2.0: limiting primaries are degenerate");
        let input_params = JmhParams::new(&Chromaticities::AP0).ok_or_else(bad_prims)?;
        let reach_params = JmhParams::new(&Chromaticities::AP1).ok_or_else(bad_prims)?;
        let limit_params = JmhParams::new(&config.limiting_primaries).ok_or_else(bad_prims)?;

        let ap0_rgb_to_xyz = rgb_to_xyz_matrix(&Chromaticities::AP0, 1.0);
        let ap1_rgb_to_xyz = rgb_to_xyz_matrix(&Chromaticities::AP1, 1.0);
        let ap0_to_ap1 = mul_mm(
            &ap0_rgb_to_xyz,
            &invert(&ap1_rgb_to_xyz).ok_or_else(bad_prims)?,
        );
        let ap1_to_ap0 = mul_mm(
            &ap1_rgb_to_xyz,
            &invert(&ap0_rgb_to_xyz).ok_or_else(bad_prims)?,
        );

        let ts = TsParams::new(peak);
        let limit_j_max = input_params.y_to_j(peak);
        let model_gamma_inv = 1.0 / model_gamma();

        let reach_m = make_reach_m_table(&reach_params, limit_j_max);

        let sat = (CHROMA_EXPAND - (CHROMA_EXPAND * CHROMA_EXPAND_FACT) * ts.log_peak).max(0.2);
        let sat_thr = CHROMA_EXPAND_THR / peak;
        let compr = CHROMA_COMPRESS + (CHROMA_COMPRESS * CHROMA_COMPRESS_FACT) * ts.log_peak;
        let chroma_compress_scale = powf(0.03379 * peak, 0.30596) - 0.45135;

        let mid_j = input_params.y_to_j(ts.c_t * REF_LUMINANCE);
        let focus_dist = FOCUS_DISTANCE + FOCUS_DISTANCE * FOCUS_DISTANCE_SCALING * ts.log_peak;
        let lower_hull_gamma_inv = 1.0 / (1.14 + 0.07 * ts.log_peak);

        // Gamut cusp table on a corner-aware hue grid.
        let reach_corners = find_reach_corners_table(&reach_params, limit_j_max, ts.forward_limit);
        let (limit_rgb_corners, limit_jmh_corners) =
            build_limiting_cusp_corners_tables(&limit_params, peak);
        let (sorted_hues, unique_hues) =
            extract_sorted_cube_hues(&reach_corners, &limit_jmh_corners);
        let hues = build_hue_table(&sorted_hues, unique_hues);

        let mut cusps = [[0.0f32; 2]; TOTAL_TABLE_SIZE];
        let mut previous = [0.0f32; 2];
        for i in BASE_INDEX..BASE_INDEX + TABLE_SIZE {
            let jm = find_display_cusp_for_hue(
                hues[i],
                &limit_rgb_corners,
                &limit_jmh_corners,
                &limit_params,
                &mut previous,
            );
            cusps[i] = [jm[0], jm[1] * (1.0 + SMOOTH_M * SMOOTH_CUSPS)];
        }
        cusps[0] = cusps[TABLE_SIZE];
        cusps[BASE_INDEX + TABLE_SIZE] = cusps[BASE_INDEX];

        // Narrow the per-pixel hue search to the table's deviation from uniform.
        let mut hue_linearity_search_range = [0i32, 1];
        for (i, &h) in hues
            .iter()
            .enumerate()
            .take(BASE_INDEX + TABLE_SIZE)
            .skip(BASE_INDEX)
        {
            let pos = BASE_INDEX + (h.max(0.0) as usize).min(TABLE_SIZE - 1);
            let delta = i as i32 - pos as i32;
            hue_linearity_search_range[0] = hue_linearity_search_range[0].min(delta);
            hue_linearity_search_range[1] = hue_linearity_search_range[1].max(delta + 1);
        }

        // Upper hull gamma per hue: the smallest gamma whose analytic boundary
        // sits outside the true display hull at five test heights.
        let mut upper_hull_gamma = [0.0f32; TOTAL_TABLE_SIZE];
        for i in BASE_INDEX..BASE_INDEX + TABLE_SIZE {
            let hue = hues[i];
            let jm_cusp = cusps[i];
            let data = generate_gamma_test_data(jm_cusp, limit_j_max, mid_j, focus_dist);
            let fits = |gamma: f32| {
                evaluate_gamma_fit(
                    jm_cusp,
                    hue,
                    &data,
                    1.0 / gamma,
                    peak,
                    limit_j_max,
                    lower_hull_gamma_inv,
                    &limit_params,
                )
            };
            let mut low = GAMMA_MINIMUM;
            let mut high = low + GAMMA_SEARCH_STEP;
            let mut outside = false;
            while !outside && high < GAMMA_MAXIMUM {
                if fits(high) {
                    outside = true;
                } else {
                    low = high;
                    high += GAMMA_SEARCH_STEP;
                }
            }
            while (high - low) > GAMMA_ACCURACY {
                let test_gamma = (high + low) / 2.0;
                if fits(test_gamma) {
                    high = test_gamma;
                } else {
                    low = test_gamma;
                }
            }
            upper_hull_gamma[i] = 1.0 / high;
        }
        upper_hull_gamma[0] = upper_hull_gamma[TABLE_SIZE];
        upper_hull_gamma[BASE_INDEX + TABLE_SIZE] = upper_hull_gamma[BASE_INDEX];

        Ok(Self {
            peak_luminance: peak,
            input_params,
            limit_params,
            ts,
            ap0_to_ap1,
            ap1_to_ap0,
            limit_j_max,
            model_gamma_inv,
            sat,
            sat_thr,
            compr,
            chroma_compress_scale,
            mid_j,
            focus_dist,
            lower_hull_gamma_inv,
            hue_linearity_search_range,
            tables: Box::new(Tables {
                reach_m,
                hues,
                cusps,
                upper_hull_gamma,
            }),
        })
    }

    /// Peak display luminance this transform was built for, in cd/m².
    #[must_use]
    pub fn peak_luminance(&self) -> f32 {
        self.peak_luminance
    }

    /// Forward output transform: ACES2065-1 linear → display-linear RGB in
    /// the limiting primaries (`1.0` = 100 cd/m²).
    ///
    /// Input is first clamped to the AP1 cube `[0, forward_limit]` as the CTL
    /// does (`clamp_AP0_to_AP1`); non-finite components clamp to `0`.
    #[must_use]
    pub fn forward(&self, aces: [f32; 3]) -> [f32; 3] {
        self.forward_unclamped(self.clamp_ap0_to_ap1(aces))
    }

    /// The rendering without the AP1 clamp — what OpenColorIO's
    /// `ACES_OUTPUT_TRANSFORM_20` fixed function computes.
    fn forward_unclamped(&self, ap0: [f32; 3]) -> [f32; 3] {
        let jmh = self.input_params.rgb_to_jmh(ap0);
        let tonemapped = self.tonemap_and_compress_fwd(jmh);
        let compressed = self.gamut_compress_fwd(tonemapped);
        self.limit_params.jmh_to_rgb(compressed)
    }

    /// Inverse output transform: display-linear RGB in the limiting
    /// primaries (`1.0` = 100 cd/m²) → ACES2065-1 linear.
    ///
    /// Round-trips [`forward`](Self::forward) for colours inside the display
    /// hull; the gamut-compressed region above the analytical threshold is
    /// approximated exactly as in the CTL `outputTransform_inv`.
    #[must_use]
    pub fn inverse(&self, display_rgb: [f32; 3]) -> [f32; 3] {
        let compressed = self.limit_params.rgb_to_jmh(display_rgb);
        let tonemapped = self.gamut_compress_inv(compressed);
        let jmh = self.tonemap_and_compress_inv(tonemapped);
        self.input_params.jmh_to_rgb(jmh)
    }

    // -- stages ------------------------------------------------------------

    fn clamp_ap0_to_ap1(&self, aces: [f32; 3]) -> [f32; 3] {
        let ap1 = mul_vm(aces, &self.ap0_to_ap1);
        let lim = self.ts.forward_limit;
        // `max` then `min` so NaN lands on the lower bound.
        let c = [
            ap1[0].max(0.0).min(lim),
            ap1[1].max(0.0).min(lim),
            ap1[2].max(0.0).min(lim),
        ];
        mul_vm(c, &self.ap1_to_ap0)
    }

    /// Reach gamut M at `limit_j_max` for hue `h` (1° table, linear).
    #[inline]
    fn reach_m_from_table(&self, h: f32) -> f32 {
        let base = (h.max(0.0) as usize).min(TABLE_SIZE - 1);
        let t = h - base as f32;
        let i_lo = base + BASE_INDEX;
        lerp(self.tables.reach_m[i_lo], self.tables.reach_m[i_lo + 1], t)
    }

    /// `tonemap_and_compress_fwd`: tonescale J, then compress M.
    fn tonemap_and_compress_fwd(&self, jmh: [f32; 3]) -> [f32; 3] {
        let linear = self.input_params.j_to_y(jmh[0]) / REF_LUMINANCE;
        let tonemapped_y = self.ts.fwd(linear);
        let j_ts = self.input_params.y_to_j(tonemapped_y);
        self.chroma_compress_fwd(jmh, j_ts)
    }

    /// `tonemap_and_compress_inv`.
    fn tonemap_and_compress_inv(&self, jmh_tc: [f32; 3]) -> [f32; 3] {
        let luminance = self.input_params.j_to_y(jmh_tc[0]);
        let linear = self.ts.inv(luminance / REF_LUMINANCE);
        let j = self.input_params.y_to_j(linear * REF_LUMINANCE);
        self.chroma_compress_inv(jmh_tc, j)
    }

    /// `chroma_compress_fwd`: returns `{ tonemapped J, compressed M, h }`.
    fn chroma_compress_fwd(&self, jmh: [f32; 3], tonemapped_j: f32) -> [f32; 3] {
        let [j, m, h] = jmh;
        let mut m_compr = m;
        if m != 0.0 {
            let n_j = tonemapped_j / self.limit_j_max;
            let sn_j = (1.0 - n_j).max(0.0);
            let m_norm = chroma_compress_norm(h, self.chroma_compress_scale);
            let limit = powf(n_j, self.model_gamma_inv) * self.reach_m_from_table(h) / m_norm;
            let toe_limit = limit - 0.001;
            let toe_sn_j_sat = sn_j * self.sat;
            let toe_sqrt_n_j_sat_thr = sqrtf(n_j * n_j + self.sat_thr);
            let toe_n_j_compr = n_j * self.compr;

            // Rescale M with the tonescaled J (Hellwig model gamma keeps the
            // M/J ratio, i.e. the chromaticity, constant).
            m_compr = m * powf(tonemapped_j / j, self.model_gamma_inv);
            // Normalise by the rendering-space cusp M.
            m_compr /= m_norm;
            // Expand colourfulness (toe in reverse): shadows and mid-tones,
            // not highlights; `sat_thr` tames noise near black.
            m_compr = limit
                - toe(
                    limit - m_compr,
                    toe_limit,
                    toe_sn_j_sat,
                    toe_sqrt_n_j_sat_thr,
                    false,
                );
            // Compress: less saturated colours more, pure colours less —
            // the highlight saturation roll-off.
            m_compr = toe(m_compr, limit, toe_n_j_compr, sn_j, false);
            m_compr *= m_norm;
        }
        [tonemapped_j, m_compr, h]
    }

    /// `chroma_compress_inv`: returns `{ J, M, h }`.
    fn chroma_compress_inv(&self, jmh_tc: [f32; 3], j: f32) -> [f32; 3] {
        let [tonemapped_j, m_compr, h] = jmh_tc;
        let mut m = m_compr;
        if m_compr != 0.0 {
            let n_j = tonemapped_j / self.limit_j_max;
            let sn_j = (1.0 - n_j).max(0.0);
            let m_norm = chroma_compress_norm(h, self.chroma_compress_scale);
            let limit = powf(n_j, self.model_gamma_inv) * self.reach_m_from_table(h) / m_norm;
            let toe_limit = limit - 0.001;
            let toe_sn_j_sat = sn_j * self.sat;
            let toe_sqrt_n_j_sat_thr = sqrtf(n_j * n_j + self.sat_thr);
            let toe_n_j_compr = n_j * self.compr;

            m = m_compr / m_norm;
            m = toe(m, limit, toe_n_j_compr, sn_j, true);
            m = limit
                - toe(
                    limit - m,
                    toe_limit,
                    toe_sn_j_sat,
                    toe_sqrt_n_j_sat_thr,
                    true,
                );
            m *= m_norm;
            m *= powf(tonemapped_j / j, -self.model_gamma_inv);
        }
        [j, m, h]
    }

    /// Upper index of the hue-table interval containing `h`.
    fn lookup_hue_interval(&self, h: f32) -> usize {
        let hues = &self.tables.hues;
        let nominal = BASE_INDEX + (h.max(0.0) as usize).min(TABLE_SIZE - 1);
        let mut i = nominal;
        let mut i_lo = (nominal as i32 + self.hue_linearity_search_range[0]).max(0) as usize;
        let mut i_hi = ((nominal as i32 + self.hue_linearity_search_range[1]) as usize)
            .min(BASE_INDEX + TABLE_SIZE);
        while i_lo + 1 < i_hi {
            if h > hues[i] {
                i_lo = i;
            } else {
                i_hi = i;
            }
            i = (i_lo + i_hi) / 2;
        }
        i_hi.max(1)
    }

    fn hue_dependent_gamut_params(&self, hue: f32) -> HueDependentGamutParams {
        let i_hi = self.lookup_hue_interval(hue);
        let h_lo = self.tables.hues[i_hi - 1];
        let h_hi = self.tables.hues[i_hi];
        let t = (hue - h_lo) / (h_hi - h_lo);
        let c_lo = self.tables.cusps[i_hi - 1];
        let c_hi = self.tables.cusps[i_hi];
        let jm_cusp = [lerp(c_lo[0], c_hi[0], t), lerp(c_lo[1], c_hi[1], t)];
        HueDependentGamutParams {
            jm_cusp,
            gamma_bottom_inv: self.lower_hull_gamma_inv,
            gamma_top_inv: lerp(
                self.tables.upper_hull_gamma[i_hi - 1],
                self.tables.upper_hull_gamma[i_hi],
                t,
            ),
            focus_j: compute_focus_j(jm_cusp[0], self.mid_j, self.limit_j_max),
            analytical_threshold: lerp(jm_cusp[0], self.limit_j_max, FOCUS_GAIN_BLEND),
        }
    }

    /// `compress_gamut`.
    fn compress_gamut(
        &self,
        jmh: [f32; 3],
        jx: f32,
        hdp: &HueDependentGamutParams,
        invert: bool,
    ) -> [f32; 3] {
        let [j, m, h] = jmh;
        let slope_gain = get_focus_gain(
            jx,
            hdp.analytical_threshold,
            self.limit_j_max,
            self.focus_dist,
        );
        let j_intersect_source = solve_j_intersect(j, m, hdp.focus_j, self.limit_j_max, slope_gain);
        let gamut_slope = compute_compression_vector_slope(
            j_intersect_source,
            hdp.focus_j,
            self.limit_j_max,
            slope_gain,
        );
        let j_intersect_cusp = solve_j_intersect(
            hdp.jm_cusp[0],
            hdp.jm_cusp[1],
            hdp.focus_j,
            self.limit_j_max,
            slope_gain,
        );
        let gamut_boundary_m = find_gamut_boundary_intersection(
            hdp.jm_cusp,
            self.limit_j_max,
            hdp.gamma_top_inv,
            hdp.gamma_bottom_inv,
            j_intersect_source,
            gamut_slope,
            j_intersect_cusp,
        );
        if gamut_boundary_m <= 0.0 {
            return [j, 0.0, h];
        }
        let reach_max_m = self.reach_m_from_table(h);
        let reach_boundary_m = estimate_line_and_boundary_intersection_m(
            j_intersect_source,
            gamut_slope,
            self.model_gamma_inv,
            self.limit_j_max,
            reach_max_m,
            self.limit_j_max,
        );
        let remapped_m = remap_m(m, gamut_boundary_m, reach_boundary_m, invert);
        [j_intersect_source + remapped_m * gamut_slope, remapped_m, h]
    }

    /// `gamut_compress_fwd`.
    fn gamut_compress_fwd(&self, jmh: [f32; 3]) -> [f32; 3] {
        let [j, m, h] = jmh;
        if j <= 0.0 {
            return [0.0, 0.0, h];
        }
        if m <= 0.0 || j > self.limit_j_max {
            return [j, 0.0, h];
        }
        let hdp = self.hue_dependent_gamut_params(h);
        self.compress_gamut(jmh, j, &hdp, false)
    }

    /// `gamut_compress_inv`.
    fn gamut_compress_inv(&self, jmh: [f32; 3]) -> [f32; 3] {
        let [j, m, h] = jmh;
        if j <= 0.0 {
            return [0.0, 0.0, h];
        }
        if m <= 0.0 || j > self.limit_j_max {
            return [j, 0.0, h];
        }
        let hdp = self.hue_dependent_gamut_params(h);
        let mut jx = j;
        if jx > hdp.analytical_threshold {
            jx = self.compress_gamut(jmh, jx, &hdp, true)[0];
        }
        self.compress_gamut(jmh, jx, &hdp, true)
    }
}

impl ToneMap for Aces2OutputTransform {
    /// [`forward`](Self::forward): ACES2065-1 in, display-linear out.
    #[inline]
    fn map_rgb(&self, rgb: [f32; 3]) -> [f32; 3] {
        self.forward(rgb)
    }
}

