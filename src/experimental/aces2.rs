#[inline]
fn chroma_compress_norm(h: f32, chroma_compress_scale: f32) -> f32 {
    let hr = h / 180.0 * PI;
    let a = cosf(hr);
    let b = sinf(hr);
    let cos_hr2 = a * a - b * b;
    let sin_hr2 = 2.0 * a * b;
    let cos_hr3 = 4.0 * a * a * a - 3.0 * a;
    let sin_hr3 = 3.0 * b - 4.0 * b * b * b;
    let m = 11.34072 * a + 16.46899 * cos_hr2 + 7.88380 * cos_hr3 + 14.66441 * b
        - 6.37224 * sin_hr2
        + 9.19364 * sin_hr3
        + 77.12896;
    m * chroma_compress_scale
}

/// A "toe" that remaps `x` between 0 and `limit`
/// (<https://www.desmos.com/calculator/6vplvw14ti>).
#[inline]
fn toe(x: f32, limit: f32, k1_in: f32, k2_in: f32, invert: bool) -> f32 {
    if x > limit {
        return x;
    }
    let k2 = k2_in.max(0.001);
    let k1 = sqrtf(k1_in * k1_in + k2 * k2);
    let k3 = (limit + k1) / (limit + k2);
    if invert {
        (x * x + k1 * x) / (k3 * (x + k2))
    } else {
        let minus_b = k3 * x - k1;
        let minus_c = k2 * k3 * x;
        0.5 * (minus_b + sqrtf(minus_b * minus_b + 4.0 * minus_c))
    }
}

