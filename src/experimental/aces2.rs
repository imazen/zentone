/// R, Y, G, C, B, M — hues rotate in order.
#[inline]
fn generate_unit_cube_cusp_corners(corner: usize) -> [f32; 3] {
    let f = |v: usize| if v % CUSP_CORNER_COUNT < 3 { 1.0 } else { 0.0 };
    [f(corner + 1), f(corner + 5), f(corner + 3)]
}

fn scale3(s: f32, v: [f32; 3]) -> [f32; 3] {
    [s * v[0], s * v[1], s * v[2]]
}

fn lerp3(a: [f32; 3], b: [f32; 3], t: f32) -> [f32; 3] {
    [
        lerp(a[0], b[0], t),
        lerp(a[1], b[1], t),
        lerp(a[2], b[2], t),
    ]
}

/// Rotate six corners so the lowest hue sits at `[1]`, and pad with wrapped
/// copies at `[0]` (hue − 360) and `[7]` (hue + 360).
fn arrange_corners(
    temp_rgb: &[[f32; 3]; CUSP_CORNER_COUNT],
    temp_jmh: &[[f32; 3]; CUSP_CORNER_COUNT],
) -> (
    [[f32; 3]; TOTAL_CORNER_COUNT],
    [[f32; 3]; TOTAL_CORNER_COUNT],
) {
    let mut min_index = 0;
    for (i, c) in temp_jmh.iter().enumerate() {
        if c[2] < temp_jmh[min_index][2] {
            min_index = i;
        }
    }
    let mut rgb = [[0.0f32; 3]; TOTAL_CORNER_COUNT];
    let mut jmh = [[0.0f32; 3]; TOTAL_CORNER_COUNT];
    for i in 0..CUSP_CORNER_COUNT {
        rgb[i + 1] = temp_rgb[(i + min_index) % CUSP_CORNER_COUNT];
        jmh[i + 1] = temp_jmh[(i + min_index) % CUSP_CORNER_COUNT];
    }
    rgb[0] = rgb[CUSP_CORNER_COUNT];
    rgb[CUSP_CORNER_COUNT + 1] = rgb[1];
    jmh[0] = jmh[CUSP_CORNER_COUNT];
    jmh[CUSP_CORNER_COUNT + 1] = jmh[1];
    jmh[0][2] -= HUE_LIMIT;
    jmh[CUSP_CORNER_COUNT + 1][2] += HUE_LIMIT;
    (rgb, jmh)
}

/// `build_limiting_cusp_corners_tables`.
fn build_limiting_cusp_corners_tables(
    params: &JmhParams,
    peak_luminance: f32,
) -> (
    [[f32; 3]; TOTAL_CORNER_COUNT],
    [[f32; 3]; TOTAL_CORNER_COUNT],
) {
    let mut temp_rgb = [[0.0f32; 3]; CUSP_CORNER_COUNT];
    let mut temp_jmh = [[0.0f32; 3]; CUSP_CORNER_COUNT];
    for i in 0..CUSP_CORNER_COUNT {
        temp_rgb[i] = scale3(
            peak_luminance / REF_LUMINANCE,
            generate_unit_cube_cusp_corners(i),
        );
        temp_jmh[i] = params.rgb_to_jmh(temp_rgb[i]);
    }
    arrange_corners(&temp_rgb, &temp_jmh)
}

/// `find_reach_corners_table`: the JMh of each unit-cube corner scaled to
/// hit `limit_j`, found by bisection on the achromatic response.
fn find_reach_corners_table(
    params_reach: &JmhParams,
    limit_j_max: f32,
    forward_limit: f32,
) -> [[f32; 3]; TOTAL_CORNER_COUNT] {
    let limit_a = j_to_achromatic_n(limit_j_max, params_reach.inv_cz);
    let mut temp_jmh = [[0.0f32; 3]; CUSP_CORNER_COUNT];
    let temp_rgb = [[0.0f32; 3]; CUSP_CORNER_COUNT];
    for (i, out) in temp_jmh.iter_mut().enumerate() {
        let rgb_vector = generate_unit_cube_cusp_corners(i);
        let mut lower = 0.0f32;
        let mut upper = forward_limit;
        while (upper - lower) > REACH_CUSP_TOLERANCE {
            let test = (lower + upper) / 2.0;
            let a = params_reach.rgb_to_aab(scale3(test, rgb_vector))[0];
            if a < limit_a {
                lower = test;
            } else {
                upper = test;
            }
            if a == limit_a {
                break;
            }
        }
        *out = params_reach.rgb_to_jmh(scale3(upper, rgb_vector));
    }
    arrange_corners(&temp_rgb, &temp_jmh).1
}

/// Merge the two sorted corner-hue lists (entries `1..=6`), de-duplicating
/// equal hues. Returns the hues and the unique count.
fn extract_sorted_cube_hues(
    reach_jmh: &[[f32; 3]; TOTAL_CORNER_COUNT],
    limit_jmh: &[[f32; 3]; TOTAL_CORNER_COUNT],
) -> ([f32; MAX_SORTED_CORNERS], usize) {
    let mut sorted = [0.0f32; MAX_SORTED_CORNERS];
    let mut idx = 0;
    let mut reach_idx = 1;
    let mut limit_idx = 1;
    while reach_idx < CUSP_CORNER_COUNT + 1 || limit_idx < CUSP_CORNER_COUNT + 1 {
        // Index 7 holds the +360°-wrapped first hue, which acts as a sentinel
        // once one list is exhausted.
        let reach_hue = reach_jmh[reach_idx][2];
        let limit_hue = limit_jmh[limit_idx][2];
        if reach_hue == limit_hue {
            sorted[idx] = reach_hue;
            reach_idx += 1;
            limit_idx += 1;
        } else if reach_hue < limit_hue {
            sorted[idx] = reach_hue;
            reach_idx += 1;
        } else {
            sorted[idx] = limit_hue;
            limit_idx += 1;
        }
        idx += 1;
    }
    (sorted, idx)
}

fn build_hue_sample_interval(
    hue_table: &mut [f32; TOTAL_TABLE_SIZE],
    samples: usize,
    lower: f32,
    upper: f32,
    base: usize,
) {
    let delta = (upper - lower) / samples as f32;
    for i in 0..samples {
        hue_table[base + i] = lower + i as f32 * delta;
    }
}

/// `build_hue_table`: 360 hues, as uniform as possible while landing exactly
/// on every gamut corner hue.
fn build_hue_table(
    sorted_hues: &[f32; MAX_SORTED_CORNERS],
    unique_hues: usize,
) -> [f32; TOTAL_TABLE_SIZE] {
    let mut hue_table = [0.0f32; TOTAL_TABLE_SIZE];
    let ideal_spacing = TABLE_SIZE as f32 / HUE_LIMIT;
    let mut samples_count = [0usize; MAX_SORTED_CORNERS + 2];
    let mut last_idx = usize::MAX;
    // Ensure we can always sample at hue 0.
    let mut min_index = if sorted_hues[0] == 0.0 { 0 } else { 1 };
    for hue_idx in 0..unique_hues {
        let rounded = roundf(sorted_hues[hue_idx] * ideal_spacing).max(0.0) as usize;
        let mut nominal_idx = rounded.max(min_index).min(TABLE_SIZE - 1);
        if last_idx == nominal_idx {
            // Two hues would sample at the same index: move the previous one
            // down if there is room, otherwise this one up.
            if hue_idx > 1 && samples_count[hue_idx - 2] != samples_count[hue_idx - 1] - 1 {
                samples_count[hue_idx - 1] -= 1;
            } else {
                nominal_idx += 1;
            }
        }
        samples_count[hue_idx] = nominal_idx.min(TABLE_SIZE - 1);
        min_index = nominal_idx;
        last_idx = nominal_idx;
    }

    let mut total_samples = 0usize;
    build_hue_sample_interval(
        &mut hue_table,
        samples_count[0],
        0.0,
        sorted_hues[0],
        total_samples + 1,
    );
    total_samples += samples_count[0];
    for i in 1..unique_hues {
        let samples = samples_count[i] - samples_count[i - 1];
        build_hue_sample_interval(
            &mut hue_table,
            samples,
            sorted_hues[i - 1],
            sorted_hues[i],
            total_samples + 1,
        );
        total_samples += samples;
    }
    build_hue_sample_interval(
        &mut hue_table,
        TABLE_SIZE - total_samples,
        sorted_hues[unique_hues - 1],
        HUE_LIMIT,
        total_samples + 1,
    );

    hue_table[0] = hue_table[BASE_INDEX + TABLE_SIZE - 1] - HUE_LIMIT;
    hue_table[BASE_INDEX + TABLE_SIZE] = hue_table[BASE_INDEX] + HUE_LIMIT;
    hue_table
}

/// `find_display_cusp_for_hue`: bisect along the cube edge between the two
/// corners bracketing `hue` until the JMh hue matches.
fn find_display_cusp_for_hue(
    hue: f32,
    rgb_corners: &[[f32; 3]; TOTAL_CORNER_COUNT],
    jmh_corners: &[[f32; 3]; TOTAL_CORNER_COUNT],
    params: &JmhParams,
    previous: &mut [f32; 2],
) -> [f32; 2] {
    let mut upper_corner = 1;
    for (i, c) in jmh_corners.iter().enumerate().skip(1) {
        if c[2] > hue {
            upper_corner = i;
            break;
        }
    }
    let lower_corner = upper_corner - 1;
    if jmh_corners[lower_corner][2] == hue {
        return [jmh_corners[lower_corner][0], jmh_corners[lower_corner][1]];
    }

    let cusp_lower = rgb_corners[lower_corner];
    let cusp_upper = rgb_corners[upper_corner];
    // Still on the same edge: resume from where the previous hue ended.
    let mut lower_t = if upper_corner as f32 == previous[0] {
        previous[1]
    } else {
        0.0
    };
    let mut upper_t = 1.0f32;

    // Across the [0, 360) boundary the search directions swap; comparing
    // against the corner hues keeps the sample inside the edge's hue range.
    while (upper_t - lower_t) > DISPLAY_CUSP_TOLERANCE {
        let sample_t = (lower_t + upper_t) / 2.0;
        let jmh = params.rgb_to_jmh(lerp3(cusp_lower, cusp_upper, sample_t));
        if jmh[2] < jmh_corners[lower_corner][2] {
            upper_t = sample_t;
        } else if jmh[2] >= jmh_corners[upper_corner][2] {
            lower_t = sample_t;
        } else if jmh[2] > hue {
            upper_t = sample_t;
        } else {
            lower_t = sample_t;
        }
    }
    let sample_t = (lower_t + upper_t) / 2.0;
    let jmh = params.rgb_to_jmh(lerp3(cusp_lower, cusp_upper, sample_t));
    previous[0] = upper_corner as f32;
    previous[1] = sample_t;
    [jmh[0], jmh[1]]
}

/// `make_reach_m_table`: the reach gamut's M at `limit_j_max` per degree.
fn make_reach_m_table(params: &JmhParams, limit_j_max: f32) -> [f32; TOTAL_TABLE_SIZE] {
    let mut table = [0.0f32; TOTAL_TABLE_SIZE];
    for i in 0..TABLE_SIZE {
        let hue = i as f32 * HUE_LIMIT / TABLE_SIZE as f32;
        const SEARCH_RANGE: f32 = 50.0;
        const SEARCH_MAXIMUM: f32 = 1300.0;
        let mut low = 0.0f32;
        let mut high = low + SEARCH_RANGE;
        let mut outside = false;
        let any_below_zero = |m: f32| {
            let rgb = params.jmh_to_rgb([limit_j_max, m, hue]);
            rgb[0] < 0.0 || rgb[1] < 0.0 || rgb[2] < 0.0
        };
        while !outside && high < SEARCH_MAXIMUM {
            outside = any_below_zero(high);
            if !outside {
                low = high;
                high += SEARCH_RANGE;
            }
        }
        while high - low > 1e-2 {
            let sample_m = (high + low) / 2.0;
            if any_below_zero(sample_m) {
                high = sample_m;
            } else {
                low = sample_m;
            }
        }
        table[i + BASE_INDEX] = high;
    }
    table[0] = table[TABLE_SIZE];
    table[BASE_INDEX + TABLE_SIZE] = table[BASE_INDEX];
    table
}

const GAMMA_TEST_COUNT: usize = 5;
const GAMMA_TEST_POSITIONS: [f32; GAMMA_TEST_COUNT] = [0.01, 0.1, 0.5, 0.8, 0.99];

#[derive(Debug, Clone, Copy, Default)]
struct GammaTestData {
    j_intersect_source: f32,
    slope: f32,
    j_intersect_cusp: f32,
}

fn generate_gamma_test_data(
    jm_cusp: [f32; 2],
    limit_j_max: f32,
    mid_j: f32,
    focus_dist: f32,
) -> [GammaTestData; GAMMA_TEST_COUNT] {
    let analytical_threshold = lerp(jm_cusp[0], limit_j_max, FOCUS_GAIN_BLEND);
    let focus_j = compute_focus_j(jm_cusp[0], mid_j, limit_j_max);
    let mut data = [GammaTestData::default(); GAMMA_TEST_COUNT];
    for (d, &pos) in data.iter_mut().zip(GAMMA_TEST_POSITIONS.iter()) {
        let test_j = lerp(jm_cusp[0], limit_j_max, pos);
        let slope_gain = get_focus_gain(test_j, analytical_threshold, limit_j_max, focus_dist);
        let j_intersect_source =
            solve_j_intersect(test_j, jm_cusp[1], focus_j, limit_j_max, slope_gain);
        *d = GammaTestData {
            j_intersect_source,
            slope: compute_compression_vector_slope(
                j_intersect_source,
                focus_j,
                limit_j_max,
                slope_gain,
            ),
            j_intersect_cusp: solve_j_intersect(
                jm_cusp[0],
                jm_cusp[1],
                focus_j,
                limit_j_max,
                slope_gain,
            ),
        };
    }
    data
}

#[allow(clippy::too_many_arguments)]
fn evaluate_gamma_fit(
    jm_cusp: [f32; 2],
    hue: f32,
    data: &[GammaTestData; GAMMA_TEST_COUNT],
    top_gamma_inv: f32,
    peak_luminance: f32,
    limit_j_max: f32,
    lower_hull_gamma_inv: f32,
    limit_params: &JmhParams,
) -> bool {
    let luminance_limit = peak_luminance / REF_LUMINANCE;
    for t in data {
        let approx_limit_m = find_gamut_boundary_intersection(
            jm_cusp,
            limit_j_max,
            top_gamma_inv,
            lower_hull_gamma_inv,
            t.j_intersect_source,
            t.slope,
            t.j_intersect_cusp,
        );
        let approx_limit_j = t.j_intersect_source + t.slope * approx_limit_m;
        let rgb = limit_params.jmh_to_rgb([approx_limit_j, approx_limit_m, hue]);
        let outside_hull =
            rgb[0] > luminance_limit || rgb[1] > luminance_limit || rgb[2] > luminance_limit;
        if !outside_hull {
            return false;
        }
    }
    true
}

