/// Pre-computed CAM matrices and constants for one set of primaries.
#[derive(Debug, Clone, Copy)]
struct JmhParams {
    rgb_to_cam16_c: Mat3,
    cam16_c_to_rgb: Mat3,
    cone_response_to_aab: Mat3,
    aab_to_cone_response: Mat3,
    f_l_n: f32,
    cz: f32,
    inv_cz: f32,
    a_w_j: f32,
    inv_a_w_j: f32,
}

#[inline]
fn cone_compress_fwd_abs(rc: f32) -> f32 {
    let f_l_y = powf(rc, 0.42);
    f_l_y / (CAM_NL_OFFSET + f_l_y)
}

#[inline]
fn cone_compress_inv_abs(ra: f32) -> f32 {
    let ra_lim = ra.min(0.99);
    let f_l_y = (CAM_NL_OFFSET * ra_lim) / (1.0 - ra_lim);
    powf(f_l_y, 1.0 / 0.42)
}

#[inline]
fn cone_compress_fwd(v: f32) -> f32 {
    copysign(cone_compress_fwd_abs(fabsf(v)), v)
}

#[inline]
fn cone_compress_inv(v: f32) -> f32 {
    copysign(cone_compress_inv_abs(fabsf(v)), v)
}

#[inline]
fn achromatic_n_to_j(a: f32, cz: f32) -> f32 {
    J_SCALE * powf(a, cz)
}

#[inline]
fn j_to_achromatic_n(j: f32, inv_cz: f32) -> f32 {
    powf(j * (1.0 / J_SCALE), inv_cz)
}

impl JmhParams {
    /// `init_JMhParams(prims)`.
    fn new(prims: &Chromaticities) -> Option<Self> {
        const CAM16_PRI: Chromaticities = Chromaticities {
            red: [0.8336, 0.1735],
            green: [2.3854, -1.4659],
            blue: [0.087, -0.125],
            white: [0.333, 0.333],
        };
        let matrix_16 = xyz_to_rgb_matrix(&CAM16_PRI, 1.0)?;
        let base_cone_response_to_aab: Mat3 = [
            [2.0, 1.0, 1.0 / 9.0],
            [1.0, -12.0 / 11.0, 1.0 / 9.0],
            [1.0 / 20.0, 1.0 / 11.0, -2.0 / 9.0],
        ];
        let rgb_to_xyz = rgb_to_xyz_matrix(prims, 1.0);
        let xyz_w = mul_vm([REF_LUMINANCE; 3], &rgb_to_xyz);
        let y_w = xyz_w[1];
        let rgb_w = mul_vm(xyz_w, &matrix_16);

        let k = 1.0 / (5.0 * L_A + 1.0);
        let k4 = k * k * k * k;
        let f_l = 0.2 * k4 * (5.0 * L_A) + 0.1 * powf(1.0 - k4, 2.0) * powf(5.0 * L_A, 1.0 / 3.0);
        let f_l_n = f_l / REF_LUMINANCE;
        let cz = model_gamma();

        let d_rgb = [
            f_l_n * y_w / rgb_w[0],
            f_l_n * y_w / rgb_w[1],
            f_l_n * y_w / rgb_w[2],
        ];
        let rgb_wc = [
            d_rgb[0] * rgb_w[0],
            d_rgb[1] * rgb_w[1],
            d_rgb[2] * rgb_w[2],
        ];
        let rgb_aw = [
            cone_compress_fwd(rgb_wc[0]),
            cone_compress_fwd(rgb_wc[1]),
            cone_compress_fwd(rgb_wc[2]),
        ];
        let cone_response_to_aab = mul_mm(
            &scale_m(&IDENTITY, CAM_NL_SCALE),
            &base_cone_response_to_aab,
        );
        let a_w = cone_response_to_aab[0][0] * rgb_aw[0]
            + cone_response_to_aab[1][0] * rgb_aw[1]
            + cone_response_to_aab[2][0] * rgb_aw[2];
        let a_w_j = cone_compress_fwd_abs(f_l);

        // Prescale the CAM16 LMS responses to provide chromatic adaptation.
        let m1 = mul_mm(&rgb_to_xyz, &matrix_16);
        let m2 = scale_m(&IDENTITY, REF_LUMINANCE);
        let rgb_to_cam16 = mul_mm(&m1, &m2);
        let rgb_to_cam16_c = mul_mm(&rgb_to_cam16, &scale_diagonal(&IDENTITY, d_rgb));

        let s = 43.0 * SURROUND[2];
        let c2a = &cone_response_to_aab;
        let cone_response_to_aab_n: Mat3 = [
            [c2a[0][0] / a_w, c2a[0][1] * s, c2a[0][2] * s],
            [c2a[1][0] / a_w, c2a[1][1] * s, c2a[1][2] * s],
            [c2a[2][0] / a_w, c2a[2][1] * s, c2a[2][2] * s],
        ];

        Some(Self {
            rgb_to_cam16_c,
            cam16_c_to_rgb: invert(&rgb_to_cam16_c)?,
            cone_response_to_aab: cone_response_to_aab_n,
            aab_to_cone_response: invert(&cone_response_to_aab_n)?,
            f_l_n,
            cz,
            inv_cz: 1.0 / cz,
            a_w_j,
            inv_a_w_j: 1.0 / a_w_j,
        })
    }

    #[inline]
    fn a_to_y(&self, a: f32) -> f32 {
        cone_compress_inv_abs(self.a_w_j * a) / self.f_l_n
    }

    #[inline]
    fn j_to_y(&self, j: f32) -> f32 {
        self.a_to_y(j_to_achromatic_n(fabsf(j), self.inv_cz))
    }

    #[inline]
    fn y_to_j(&self, y: f32) -> f32 {
        let ra = cone_compress_fwd_abs(fabsf(y) * self.f_l_n);
        copysign(achromatic_n_to_j(ra * self.inv_a_w_j, self.cz), y)
    }

    #[inline]
    fn rgb_to_aab(&self, rgb: [f32; 3]) -> [f32; 3] {
        let rgb_m = mul_vm(rgb, &self.rgb_to_cam16_c);
        let rgb_a = [
            cone_compress_fwd(rgb_m[0]),
            cone_compress_fwd(rgb_m[1]),
            cone_compress_fwd(rgb_m[2]),
        ];
        mul_vm(rgb_a, &self.cone_response_to_aab)
    }

    #[inline]
    fn aab_to_jmh(&self, aab: [f32; 3]) -> [f32; 3] {
        if aab[0] <= 0.0 {
            return [0.0, 0.0, 0.0];
        }
        let j = achromatic_n_to_j(aab[0], self.cz);
        let m = sqrtf(aab[1] * aab[1] + aab[2] * aab[2]);
        let h = wrap_to_360(atan2f(aab[2], aab[1]) * 180.0 / PI);
        [j, m, h]
    }

    #[inline]
    fn rgb_to_jmh(&self, rgb: [f32; 3]) -> [f32; 3] {
        self.aab_to_jmh(self.rgb_to_aab(rgb))
    }

    #[inline]
    fn jmh_to_aab(&self, jmh: [f32; 3]) -> [f32; 3] {
        let h_rad = jmh[2] / 180.0 * PI;
        let a = j_to_achromatic_n(jmh[0], self.inv_cz);
        [a, jmh[1] * cosf(h_rad), jmh[1] * sinf(h_rad)]
    }

    #[inline]
    fn aab_to_rgb(&self, aab: [f32; 3]) -> [f32; 3] {
        let rgb_a = mul_vm(aab, &self.aab_to_cone_response);
        let rgb_m = [
            cone_compress_inv(rgb_a[0]),
            cone_compress_inv(rgb_a[1]),
            cone_compress_inv(rgb_a[2]),
        ];
        mul_vm(rgb_m, &self.cam16_c_to_rgb)
    }

    #[inline]
    fn jmh_to_rgb(&self, jmh: [f32; 3]) -> [f32; 3] {
        self.aab_to_rgb(self.jmh_to_aab(jmh))
    }
}

