    /// Hue is compared circularly and only when M is large enough for the
    /// angle to be numerically meaningful.
    fn assert_jmh_close(
        got: [f32; 3],
        want: [f32; 3],
        tol_j: f32,
        tol_m: f32,
        tol_h: f32,
        ctx: &str,
    ) {
        assert_jmh_close_rel(got, want, tol_j, tol_m, 1e-4, tol_h, ctx);
    }

    fn assert_jmh_close_rel(
        got: [f32; 3],
        want: [f32; 3],
        tol_j: f32,
        tol_m: f32,
        rel_m: f32,
        tol_h: f32,
        ctx: &str,
    ) {
        assert!(
            (got[0] - want[0]).abs() <= tol_j,
            "{ctx}: J {} vs {} (tol {tol_j})",
            got[0],
            want[0]
        );
        let m_tol = tol_m + want[1].abs() * rel_m;
        assert!(
            (got[1] - want[1]).abs() <= m_tol,
            "{ctx}: M {} vs {} (tol {m_tol})",
            got[1],
            want[1]
        );
        if want[1] > 0.05 {
            let mut dh = (got[2] - want[2]).abs();
            if dh > 180.0 {
                dh = 360.0 - dh;
            }
            assert!(
                dh <= tol_h,
                "{ctx}: h {} vs {} (tol {tol_h})",
                got[2],
                want[2]
            );
        }
    }

