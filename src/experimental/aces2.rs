#[derive(Debug, Clone, Copy)]
struct TsParams {
    n: f32,
    n_r: f32,
    g: f32,
    t_1: f32,
    c_t: f32,
    s_2: f32,
    u_2: f32,
    m_2: f32,
    forward_limit: f32,
    log_peak: f32,
}

impl TsParams {
    /// `init_TSParams(peakLuminance)`.
    fn new(peak_luminance: f32) -> Self {
        let n = peak_luminance;
        let n_r = 100.0; // normalized white in nits (what 1.0 should be)
        let g = 1.15; // surround / contrast
        let c = 0.18; // anchor for 18% grey
        let c_d = 10.013; // output luminance of 18% grey (in nits)
        let w_g = 0.14; // change in grey between different peak luminance
        let t_1 = 0.04; // shadow toe or flare/glare compensation
        let r_hit_min = 128.0; // scene-referred value "hitting the roof" for SDR
        let r_hit_max = 896.0; // ... for 10000 nits

        let r_hit = r_hit_min + (r_hit_max - r_hit_min) * (logf(n / n_r) / logf(10000.0 / 100.0));
        let m_0 = n / n_r;
        let m_1 = 0.5 * (m_0 + sqrtf(m_0 * (m_0 + 4.0 * t_1)));
        let u = powf((r_hit / m_1) / ((r_hit / m_1) + 1.0), g);
        let m = m_1 / u;
        let w_i = logf(n / 100.0) / logf(2.0);
        let c_t = c_d / n_r * (1.0 + w_i * w_g);
        let g_ip = 0.5 * (c_t + sqrtf(c_t * (c_t + 4.0 * t_1)));
        let g_ipp2 = -(m_1 * powf(g_ip / m, 1.0 / g)) / (powf(g_ip / m, 1.0 / g) - 1.0);
        let w_2 = c / g_ipp2;
        let s_2 = w_2 * m_1;
        let u_2 = powf((r_hit / m_1) / ((r_hit / m_1) + w_2), g);
        let m_2 = m_1 / u_2;

        Self {
            n,
            n_r,
            g,
            t_1,
            c_t,
            s_2,
            u_2,
            m_2,
            forward_limit: 8.0 * r_hit,
            log_peak: log10f(n / n_r),
        }
    }

    /// `tonescale_fwd`: scene-referred linear (1.0 = 100 nits) → cd/m².
    #[inline]
    fn fwd(&self, x: f32) -> f32 {
        let f = self.m_2 * powf(x.max(0.0) / (x + self.s_2), self.g);
        let h = (f * f / (f + self.t_1)).max(0.0);
        h * self.n_r
    }

    /// `tonescale_inv`: cd/m² → scene-referred linear.
    #[inline]
    fn inv(&self, y: f32) -> f32 {
        let z = y.min(self.n / (self.u_2 * self.n_r)).max(0.0);
        let h = (z + sqrtf(z * (4.0 * self.t_1 + z))) / 2.0;
        self.s_2 / (powf(self.m_2 / h, 1.0 / self.g) - 1.0)
    }
}

