//! ACES 2.0 Output Transform — Hellwig 2022 JMh tonescale, chroma
//! compression, and gamut compression.
//!
//! A port of the ACES 2.0 rendering from the Academy's reference CTL
//! (`Lib.Academy.OutputTransform.ctl` / `Lib.Academy.Tonescale.ctl`,
//! <https://github.com/aces-aswf/aces-core>, `main` as of 2025-10). The
//! pipeline is:
//!
//! ```text
//! ACES2065-1 (AP0) linear ─ clamp to AP1 [0, forward_limit]
//!   → Hellwig 2022 JMh (input CAM params)
//!   → tonescale J  +  chroma compression of M
//!   → gamut compression of (J, M) to the limiting display's hull
//!   → JMh → display-linear RGB in the limiting primaries, 1.0 = 100 cd/m²
//! ```
//!
//! Display encoding (sRGB / BT.1886 / PQ / HLG OETFs) is out of scope here —
//! zentone's `pipeline` and `linear-srgb` handle that. The transform also
//! exposes [`Aces2OutputTransform::inverse`] (display-linear → AP0), which
//! matches the CTL `outputTransform_inv`.
//!
//! **Parity.** The forward stages are held to OpenColorIO 2.5's built-in
//! ACES 2.0 fixed functions (`reference-checks/golden/aces2_ocio_*.csv`,
//! generated by `reference-checks/aces2_ocio_reference.py`) in the unit
//! tests at the bottom of this file. Two deliberate deviations from the CTL
//! text, both matching OpenColorIO: the upper-hull gamma interpolation weight
//! is normalised by the hue interval width (`(h - h_lo) / (h_hi - h_lo)`; the
//! CTL's `interpolation_weight` returns the un-normalised `h - h_lo`, which
//! is only exact for the 1° intervals), and hue is looked up against the
//! 360-entry nominal table rather than the 362-entry padded one.
//!
//! **Cost.** Per pixel: two CAM transforms (4 `pow`), the tonescale (2
//! `pow`), and the compression math — scalar only in this first cut, no SIMD
//! strip kernel. Construction builds three 360-entry hue tables by bisection
//! (reach M, display cusp, upper-hull gamma), on the order of 10⁵ CAM
//! evaluations; build one transform per output configuration and reuse it.

